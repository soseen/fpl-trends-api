import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
import prettier from "prettier";

const config = ts.readConfigFile("tsconfig.json", ts.sys.readFile);
const parsed = ts.parseJsonConfigFileContent(
  config.config,
  ts.sys,
  process.cwd(),
);
const program = ts.createProgram(parsed.fileNames, parsed.options);
const checker = program.getTypeChecker();
const sources = [
  ["getManagerSummary", "ManagerSummaryResponse", "ManagerSummary"],
  ["getManagerTrajectory", "ManagerTrajectoryResponse", "ManagerTrajectory"],
  ["getRangeRank", "RangeRankResponse", "ManagerRangeRank"],
  ["getManagerComparison", "ManagerComparisonResponse", "ManagerComparison"],
  ["getTeamImpact", "TeamImpactResponse", "TeamImpact"],
  ["getManagerTransfers", "ManagerTransfersResponse", "ManagerTransfers"],
  ["getCaptainImpact", "CaptainImpactResponse", "CaptainImpact"],
];
function schema(type, depth = 0) {
  if (depth > 30) throw new Error("Recursive API contract");
  if (type.flags & ts.TypeFlags.StringLiteral)
    return `z.literal(${JSON.stringify(type.value)})`;
  if (type.flags & ts.TypeFlags.NumberLiteral)
    return `z.literal(${type.value})`;
  if (type.flags & ts.TypeFlags.String) return "z.string()";
  if (type.flags & ts.TypeFlags.Number) return "z.number().finite()";
  if (type.flags & (ts.TypeFlags.Boolean | ts.TypeFlags.BooleanLiteral))
    return "z.boolean()";
  if (type.flags & ts.TypeFlags.Null) return "z.null()";
  if (type.isUnion()) {
    const members = [
      ...new Set(
        type.types
          .filter((t) => !(t.flags & ts.TypeFlags.Undefined))
          .map((t) => schema(t, depth + 1)),
      ),
    ];
    return members.length === 1
      ? members[0]
      : `z.union([${members.join(",")}])`;
  }
  if (checker.isArrayType(type))
    return `z.array(${schema(checker.getTypeArguments(type)[0], depth + 1)})`;
  if (type.flags & ts.TypeFlags.Object)
    return `z.object({${checker
      .getPropertiesOfType(type)
      .map((property) => {
        const declaration =
          property.valueDeclaration ?? property.declarations?.[0];
        if (!declaration)
          throw new Error(`Missing declaration: ${property.name}`);
        return `${JSON.stringify(property.name)}:${schema(checker.getTypeOfSymbolAtLocation(property, declaration), depth + 1)}${property.flags & ts.SymbolFlags.Optional ? ".optional()" : ""}`;
      })
      .join(",")}})`;
  throw new Error(`Unsupported API type: ${checker.typeToString(type)}`);
}
const declarations = sources
  .map(([file, exported, name]) => {
    const source = program.getSourceFile(
      path.resolve(`src/managers/${file}.ts`),
    );
    const symbol = source && checker.getSymbolAtLocation(source);
    const entry =
      symbol &&
      checker.getExportsOfModule(symbol).find((s) => s.name === exported);
    if (!entry) throw new Error(`Missing ${exported}`);
    return `export const ${name}Schema=${schema(checker.getDeclaredTypeOfSymbol(entry))};\nexport type ${name}=z.infer<typeof ${name}Schema>;`;
  })
  .join("\n");
const envelope = `
const errorSchema=z.object({code:z.string(),message:z.string(),retryable:z.boolean()});
const section=<T extends z.ZodType>(data:T)=>z.discriminatedUnion("status",[z.object({status:z.literal("ready"),data}),z.object({status:z.literal("error"),error:errorSchema})]);
export const ReadyAnalysisSchema=z.object({state:z.literal("ready"),season:z.string(),entryId:z.number().int(),startGw:z.number().int(),endGw:z.number().int(),revision:z.string(),generatedAt:z.string().datetime(),stale:z.boolean(),sectionGeneratedAt:z.record(z.string(),z.string().datetime()),sectionErrors:z.record(z.string(),errorSchema),sections:z.object({
summary:section(ManagerSummarySchema),trajectory:section(ManagerTrajectorySchema),rangeRank:section(ManagerRangeRankSchema),comparison:section(ManagerComparisonSchema),teamImpact:section(TeamImpactSchema),transfers:section(ManagerTransfersSchema),captainImpact:section(CaptainImpactSchema)
})});
export type ReadyAnalysis=z.infer<typeof ReadyAnalysisSchema>;
export const AnalysisResponseSchema=z.discriminatedUnion("state",[
ReadyAnalysisSchema,
z.object({state:z.literal("preparing"),message:z.string(),retryAfter:z.number(),jobStatus:z.enum(["queued","running"])}),
z.object({state:z.literal("failed"),error:errorSchema})]);
export type AnalysisResponse=z.infer<typeof AnalysisResponseSchema>;
`;
const raw = `// Generated by fpl-trends-api/scripts/generate-analytics-contracts.mjs. Do not edit.\nimport { z } from "zod";\n${declarations}\n${envelope}`;
const targets = ["src/analytics/contracts.generated.ts"];
if (fs.existsSync("../fpl-trends-app/src/queries"))
  targets.push(
    "../fpl-trends-app/src/queries/analytics-contracts.generated.ts",
  );
for (const file of targets) {
  const code = await prettier.format(raw, {
    ...(await prettier.resolveConfig(file)),
    plugins: [],
    parser: "typescript",
  });
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(file) ||
      fs.readFileSync(file, "utf8").replaceAll("\r\n", "\n") !==
        code.replaceAll("\r\n", "\n")
    )
      throw new Error(`${file} is stale. Run npm run contracts:generate`);
    continue;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, code);
}
